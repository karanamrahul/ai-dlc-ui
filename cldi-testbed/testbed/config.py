"""Config loading: boards.json (lab topology), thresholds.json (signatures + gates)."""
import copy
import json
import os
import re

PKG_DIR = os.path.dirname(os.path.abspath(__file__))
SIM_LABEL = "SIMULATED - generated by the testbed sim backend; NOT measured on hardware"
DRIVERS = ("ath10k", "ath11k", "ath12k")


def load_json(path):
    with open(path) as f:
        return json.load(f)


def write_json(path, obj):
    os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
    with open(path, "w") as f:
        json.dump(obj, f, indent=2, sort_keys=False)
        f.write("\n")


def deep_merge(base, over):
    out = copy.deepcopy(base)
    for k, v in (over or {}).items():
        if isinstance(v, dict) and isinstance(out.get(k), dict):
            out[k] = deep_merge(out[k], v)
        else:
            out[k] = copy.deepcopy(v)
    return out


def load_thresholds(path=None):
    thr = load_json(os.path.join(PKG_DIR, "thresholds.json"))
    if path:
        thr = deep_merge(thr, load_json(path))
    return thr


def load_boards(path=None):
    cfg = load_json(path or os.path.join(PKG_DIR, "boards.json"))
    for role in ("dut", "peer"):
        if role not in cfg:
            raise ValueError(f"boards.json: missing '{role}' section")
        drv = cfg[role].get("driver")
        if drv not in DRIVERS:
            raise ValueError(f"boards.json: {role}.driver must be one of {DRIVERS}, got {drv!r}")
    return cfg


class _Strict(dict):
    def __missing__(self, key):
        raise KeyError(f"template variable {{{key}}} not defined in boards.json vars")


def render(cmd, variables):
    """Fill {var} placeholders from boards.json vars; unknown vars are an error."""
    return cmd.format_map(_Strict(variables))


class Board:
    """One board: its config, its transport, and the template variables it contributes."""

    def __init__(self, role, cfg, transport):
        self.role = role
        self.cfg = cfg
        self.t = transport
        self.name = cfg.get("name", role)
        self.driver = cfg["driver"]
        self.qsdk = bool(cfg.get("qsdk", False))
        self.caps = set(cfg.get("capabilities", []))
        self.paths = cfg.get("paths", {})

    @property
    def vars(self):
        return dict(self.cfg.get("vars", {}))


def template_vars(dut, peer, loop=None):
    v = {}
    v.update(peer.vars)
    v.update(dut.vars)  # DUT wins on clashes; keep names distinct in boards.json
    v["driver"] = dut.driver
    if loop is not None:
        v["loop"] = loop
    return v


